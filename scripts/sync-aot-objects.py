#!/usr/bin/env python3
"""Rewrite ZE_AOT_OBJECTS in Ze.xcodeproj/project.pbxproj from aot/*.o.

The images are linked by listing every object in OTHER_LDFLAGS, and that list
was hand-maintained: when a recording produced a new image (libwebp, pybinascii)
the file sat in aot/ while the app kept linking the old set, so the toggle
worked and the new library stayed slow. Run this after dropping a new
recording into aot/.
"""
import glob
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
objects = sorted(os.path.basename(p) for p in glob.glob(os.path.join(root, 'aot', '*.o')))
if not objects:
    sys.exit('no aot/*.o found')

value = ' '.join('$(SRCROOT)/aot/' + name for name in objects)
path = os.path.join(root, 'Ze.xcodeproj', 'project.pbxproj')
with open(path, encoding='utf-8', newline='') as handle:
    text = handle.read()

updated, count = re.subn(
    r'(ZE_AOT_OBJECTS = ")[^"]*(";)',
    lambda match: match.group(1) + value + match.group(2),
    text,
)
if count == 0:
    sys.exit('ZE_AOT_OBJECTS not found in project.pbxproj')

with open(path, 'w', encoding='utf-8', newline='') as handle:
    handle.write(updated)

print(f'{count} ZE_AOT_OBJECTS line(s) updated with {len(objects)} images')
for name in objects:
    print('  ' + name)

# Import the actual package provenance alongside a replacement recording set.
# This file is generated by strict recording; never substitute the future target
# versions while the old objects are still linked.
versions_file = os.path.join(root, 'aot', 'VERSIONS.txt')
with open(versions_file, encoding='utf-8') as handle:
    versions = dict(re.findall(r'^([a-z0-9+_.-]+)-(\d[^\s]*-r\d+)$', handle.read(), re.M))
accel_path = os.path.join(root, 'Agent', 'ISH', 'AOJITAcceleration.swift')
with open(accel_path, encoding='utf-8', newline='') as handle:
    accel = handle.read()
line_end = '\r\n' if '\r\n' in accel else '\n'
body = line_end.join(f'        "{pkg}": "{ver}",' for pkg, ver in sorted(versions.items()))
accel, changed = re.subn(r'(static let imageVersions: \[String: String\] = \[)\r?\n.*?\r?\n    \]',
                         lambda m: m.group(1) + line_end + body + line_end + '    ]', accel,
                         count=1, flags=re.S)
if changed != 1:
    sys.exit('imageVersions table not found')
with open(accel_path, 'w', encoding='utf-8', newline='') as handle:
    handle.write(accel)
print(f'imageVersions updated from actual VERSIONS.txt ({len(versions)} packages)')
